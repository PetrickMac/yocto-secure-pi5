#!/usr/bin/env bash
# Clone upstream layers into layers/ and keep them at the exact commits
# recorded in layers.lock, so every build uses the same layer sources.
#
#   ./scripts/fetch-layers.sh            # clone missing layers, check out the
#                                        # commits pinned in layers.lock
#                                        # (first run: no lock yet, so pin the
#                                        # current branch tips and write it)
#   ./scripts/fetch-layers.sh --update   # pull each layer to its branch tip
#                                        # and re-pin layers.lock
#
# Workflow: run --update on purpose, review `git diff layers.lock`, commit it.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
LAYERS_DIR="$ROOT/layers"
LOCK="$ROOT/layers.lock"

UPDATE=0
case "${1:-}" in
  "") ;;
  --update) UPDATE=1 ;;
  *) echo "usage: $0 [--update]" >&2; exit 2 ;;
esac

# name | url | branch
LAYERS=(
  "poky|https://git.yoctoproject.org/poky|scarthgap"
  "meta-openembedded|https://git.openembedded.org/meta-openembedded|scarthgap"
  "meta-raspberrypi|https://git.yoctoproject.org/meta-raspberrypi|scarthgap"
  "meta-lts-mixins|https://git.yoctoproject.org/meta-lts-mixins|scarthgap/u-boot"
)

# No lock file yet means nothing is pinned: treat this run like --update.
WRITE_LOCK=$UPDATE
if [[ ! -f "$LOCK" ]]; then
  echo "==> no layers.lock yet, pinning current branch tips"
  WRITE_LOCK=1
fi

# Print "<branch> <commit>" for a layer from layers.lock, or nothing.
lock_entry() {
  awk -v n="$1" '$1 == n { print $2, $3; exit }' "$LOCK"
}

mkdir -p "$LAYERS_DIR"

for entry in "${LAYERS[@]}"; do
  IFS='|' read -r name url branch <<<"$entry"
  dest="$LAYERS_DIR/$name"

  if [[ ! -d "$dest/.git" ]]; then
    echo "==> cloning $name ($branch)"
    git clone --branch "$branch" "$url" "$dest"
  else
    echo "==> $name exists"
  fi

  if (( WRITE_LOCK )); then
    # Move to the newest commit on the branch; it gets pinned below.
    git -C "$dest" fetch origin "$branch"
    git -C "$dest" checkout "$branch"
    git -C "$dest" merge --ff-only "origin/$branch"
    continue
  fi

  read -r lock_branch commit < <(lock_entry "$name") || true
  if [[ -z "${commit:-}" ]]; then
    echo "!! $name is not in layers.lock; run with --update to pin it" >&2
    exit 1
  fi
  if [[ "$lock_branch" != "$branch" ]]; then
    echo "!! $name: layers.lock says branch '$lock_branch' but this script" \
         "says '$branch'; run with --update to re-pin" >&2
    exit 1
  fi

  # Fetch only if the pinned commit isn't already in the local clone.
  if ! git -C "$dest" cat-file -e "$commit^{commit}" 2>/dev/null; then
    git -C "$dest" fetch origin "$branch"
  fi
  echo "    checking out pinned $commit"
  # Detached HEAD on purpose: we are on a fixed commit, not following a branch.
  git -C "$dest" -c advice.detachedHead=false checkout --detach "$commit"
  unset lock_branch commit
done

if (( WRITE_LOCK )); then
  {
    echo "# Generated by scripts/fetch-layers.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ)"
    echo "# name branch commit"
    for entry in "${LAYERS[@]}"; do
      IFS='|' read -r name _ branch <<<"$entry"
      echo "$name $branch $(git -C "$LAYERS_DIR/$name" rev-parse HEAD)"
    done
  } > "$LOCK"
  echo
  echo "Pinned revisions written to layers.lock (commit it to keep the pin):"
else
  echo
  echo "Layers checked out at the revisions pinned in layers.lock:"
fi
cat "$LOCK"
