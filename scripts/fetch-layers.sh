#!/usr/bin/env bash
# Clone upstream layers into layers/ on pinned branches, then record the exact
# commits in layers.lock so a build can be reproduced later.
#
#   ./scripts/fetch-layers.sh            # clone missing layers, write lock
#   ./scripts/fetch-layers.sh --update   # also git pull existing layers
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
LAYERS_DIR="$ROOT/layers"
LOCK="$ROOT/layers.lock"
UPDATE="${1:-}"

# name | url | branch
LAYERS=(
  "poky|https://git.yoctoproject.org/poky|scarthgap"
  "meta-openembedded|https://git.openembedded.org/meta-openembedded|scarthgap"
  "meta-raspberrypi|https://git.yoctoproject.org/meta-raspberrypi|scarthgap"
  "meta-lts-mixins|https://git.yoctoproject.org/meta-lts-mixins|scarthgap/u-boot"
)

mkdir -p "$LAYERS_DIR"

for entry in "${LAYERS[@]}"; do
  IFS='|' read -r name url branch <<<"$entry"
  dest="$LAYERS_DIR/$name"
  if [[ -d "$dest/.git" ]]; then
    echo "==> $name exists"
    if [[ "$UPDATE" == "--update" ]]; then
      git -C "$dest" fetch origin "$branch"
      git -C "$dest" checkout "$branch"
      git -C "$dest" pull --ff-only origin "$branch"
    fi
  else
    echo "==> cloning $name ($branch)"
    git clone --branch "$branch" "$url" "$dest"
  fi
done

{
  echo "# Generated by scripts/fetch-layers.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ)"
  echo "# name branch commit"
  for entry in "${LAYERS[@]}"; do
    IFS='|' read -r name _ branch <<<"$entry"
    echo "$name $branch $(git -C "$LAYERS_DIR/$name" rev-parse HEAD)"
  done
} > "$LOCK"

echo
echo "Pinned revisions written to layers.lock:"
cat "$LOCK"
